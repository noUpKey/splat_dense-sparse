"""Camera colour families refitted on a frozen model (uwsplat/eval/camera_families.py).

python -m tests.test_camera_families      (CPU, under a minute)

Checks: every family reproduces data generated by its own model; the shared-M family's alternating least squares
recovers M diag(g_k) up to its gauge; on a toy scene whose photos are the render times smoothly varying per-channel
gains, the gain families predict an interior held-out frame almost exactly while identity does not.
"""
import os
import tempfile

import numpy as np
import torch

from tests.test_uncertainty import H, W, F, look_view, params_for
from uwsplat.common.io import save_json, save_rgb
from uwsplat.eval.camera_families import apply, fit_C, fit_frame, interpolate
from uwsplat.eval.uncertainty import render_variant
from uwsplat.gs.medium import WaterMedium


def main():
    torch.manual_seed(0)
    X = torch.rand(500, 3, dtype=torch.float64)
    Wt, bt = torch.eye(3, dtype=torch.float64) + 0.1 * torch.randn(3, 3, dtype=torch.float64), \
        0.05 * torch.randn(3, dtype=torch.float64)
    g = torch.tensor([1.2, 0.8, 1.1], dtype=torch.float64)
    cases = {"A": X @ Wt.T + bt, "B": X @ Wt.T, "D": X * g, "Do": X * g + bt, "E": 1.3 * X}
    for fam, Y in cases.items():
        prm = fit_frame(fam, X.float(), Y.float())
        err = float((apply(fam, X.float().reshape(10, 50, 3), prm).reshape(-1, 3).double() - Y).abs().max())
        assert err < 1e-4, (fam, err)
    # shared M + gains
    M = torch.eye(3, dtype=torch.float64) + 0.2 * torch.randn(3, 3, dtype=torch.float64)
    gs = torch.exp(0.2 * torch.randn(6, 3, dtype=torch.float64))
    Xs = [torch.rand(400, 3, dtype=torch.float64) for _ in range(6)]
    Ys = [(x * gk) @ M.T for x, gk in zip(Xs, gs)]
    Mf, gf = fit_C([x.float() for x in Xs], [y.float() for y in Ys], iters=200)
    for x, y, gk in zip(Xs, Ys, gf):
        assert float(((x * gk) @ Mf.T - y).abs().max()) < 1e-3
    assert torch.allclose(torch.log(gf).mean(0), torch.zeros(3, dtype=torch.float64), atol=1e-9)   # gauge

    # toy scene: photos = render x per-channel gains that drift smoothly with the frame index
    import uwsplat.eval.camera_families as cf
    import uwsplat.eval.heldout as ho
    try:
        ho.lpips(torch.rand(16, 16, 3), torch.rand(16, 16, 3))
    except Exception:
        cf._scores.__globals__["lpips"] = lambda a, b, net="vgg": 0.0     # no network weights offline
    xs = np.linspace(-1.2, 1.2, 9)
    p = params_for([[x, y, 5.0] for x in xs for y in (-0.4, 0.0, 0.4)])
    medium = WaterMedium(np.array([0.2, 0.3, 0.4]), np.array([0.3, 0.2, 0.1]), np.array([0.2, 0.2, 0.2]), 1)
    splits = ["test", "train", "train", "test", "train", "train", "train"]
    views = [look_view([0.15 * i - 0.45, 0.0, 0.0], target=(0.15 * i - 0.45, 0.0, 5.0), split=s, idx=i)
             for i, s in enumerate(splits)]
    gain = lambda i: torch.exp(0.08 * i * torch.tensor([1.0, -0.6, 0.4]))
    with tempfile.TemporaryDirectory() as d:
        images = []
        for v in views:
            img = (render_variant(p, v, medium, 0, "torch", None, "base")["image"] * gain(v.idx)).clamp(0, 1)
            save_rgb(os.path.join(d, "images", v.stem + ".png"), (img.numpy() * 255 + 0.5).astype(np.uint8))
            R, t = v.viewmat[:3, :3].numpy(), v.viewmat[:3, 3].numpy()
            images.append({"name": v.name, "file": f"images/{v.stem}.png", "registered": True, "split": v.split,
                           "R": R.tolist(), "t": t.tolist()})
        cam = {"model": "PINHOLE", "width": W, "height": H, "fx": F, "fy": F, "cx": W / 2, "cy": H / 2}
        save_json(os.path.join(d, "sfm", "scene.json"), {"scene": "toy", "camera": cam, "images": images})
        os.makedirs(os.path.join(d, "gs", "toy"))
        torch.save({"params": {k: v.clone() for k, v in p.items()}, "cfg": {"downscale": 1.0, "backend": "torch",
                    "sh_degree": 0}, "medium": medium.state_dict(), "bg": None,
                    "appearance": {"A": torch.zeros(5, 3, 3), "b": torch.zeros(5, 3)}},
                   os.path.join(d, "gs", "toy", "ckpt.pt"))
        res = cf.run(d, "toy", device="cpu", backend="torch", stride=1)
        interior = res["test"]["f003.png"]
        assert interior["D"]["psnr"] > interior["identity"]["psnr"] + 5, interior
        assert interior["C"]["psnr"] > interior["identity"]["psnr"] + 5, interior
        assert os.path.exists(os.path.join(d, "eval", "toy", "camera_families.json"))
        print("camera families test passed; interior test frame PSNR:",
              {k: round(interior[k]["psnr"], 2) for k in ("identity", "trained", "A", "B", "C", "D", "Do", "E")})


if __name__ == "__main__":
    main()
